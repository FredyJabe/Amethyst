    public static BlockInfo ForState(ushort state)
    {
        int lo = 0, hi = Blocks.Length - 1;
        while (lo <= hi)
        {
            int mid = lo + (hi - lo) / 2;
            BlockInfo b = Blocks[mid];
            if (state < b.First) hi = mid - 1;
            else if (state > b.Last) lo = mid + 1;
            else return b;
        }
        return new BlockInfo(state, state, -1, 0, 0, 0);
    }

    public static bool IsHarvestable(BlockInfo block, int heldItem)
    {
        if (block.HarvestMask == 0) return true;
        return Tools.TryGetValue(heldItem, out ToolInfo held) &&
            ((block.HarvestMask >> held.Tier) & 1) != 0 &&
            held.Kind == block.ToolKind;
    }

    public static int RequiredMilliseconds(ushort state, int heldItem)
    {
        BlockInfo info = ForState(state);
        if (info.Hardness < 0) return int.MaxValue;
        if (info.Hardness == 0) return 0;
        bool effective = Tools.TryGetValue(heldItem, out ToolInfo held) &&
            held.Kind == info.ToolKind;
        bool canHarvest = IsHarvestable(info, heldItem);
        double speed = effective ? held.Speed : 1.0;
        double ticks = info.Hardness * (canHarvest ? 30.0 : 100.0) / speed;
        return (int)Math.Clamp(Math.Ceiling(ticks * 50.0), 0, int.MaxValue);
    }
